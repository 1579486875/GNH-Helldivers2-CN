def human(n):
    for u in ("B", "KB", "MB", "GB"):
        if n < 1024 or u == "GB":
            return "%.1f %s" % (n, u)
        n /= 1024.0

def first_sentence(s, n=76):
    s = (s or "").replace("\n", " ").strip()
    for sep in ("。", ". ", "！", "；"):
        i = s.find(sep)
        if 0 < i < n:
            return s[:i + len(sep)]
    return s[:n] + ("…" if len(s) > n else "")

